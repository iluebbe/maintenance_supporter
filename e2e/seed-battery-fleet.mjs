/** Seed a realistic Battery Notes fleet into ha-maint for testing the
 *  battery-fleet discovery/setup end to end.
 *
 *  1. Writes a package of template battery sensors (registry-real source
 *     entities) into docker/config-dev/packages/ across a realistic type mix
 *     with varied levels (some below the low threshold) — config-dev is
 *     gitignored, so the FIXTURE lives here (committed) and is injected.
 *  2. Ensures the packages include + restarts ha-maint.
 *  3. Drives Battery Notes' own config flow (user -> entity -> battery) per
 *     source entity, so the note config entries are always schema-valid.
 *  4. Streaks battery_last_replaced via battery_notes.set_battery_replaced
 *     (datetime_replaced), relative to HA's clock (faketime-aware), so the
 *     prediction has old / due-soon / fresh spread.
 *
 *  Requires battery_notes installed in the mounted custom_components (dev-only,
 *  gitignored) — see the docker memory. Run: node e2e/seed-battery-fleet.mjs
 */
import fs from "fs";
import { execSync } from "child_process";

const REST = "http://127.0.0.1:8125";
const CFG = new URL("../docker/config-dev/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const log = (...a) => console.log(...a);
const j = (r) => r.json();

// (name, battery_type, quantity, level%, months_since_replaced)
const FLEET = [
  ["Living Room Motion", "CR2450", 1, 8, 20],
  ["Front Door Lock", "AA", 4, 12, 14],
  ["Kitchen Smoke Alarm", "9V", 1, 55, 6],
  ["Bedroom Thermostat", "AA", 2, 5, 22],
  ["Garage Remote", "CR2032", 1, 70, 10],
  ["Backyard Sensor", "AAA", 2, 9, 18],
  ["Office Motion", "CR2450", 1, 40, 8],
  ["Hallway Smoke Alarm", "9V", 1, 88, 2],
  ["Patio Door Sensor", "CR2032", 1, 14, 16],
  ["Basement Leak Sensor", "CR2", 1, 60, 5],
  ["Kids Room Thermostat", "AA", 2, 33, 12],
  ["Bathroom Humidity", "AAA", 2, 6, 24],
  ["Shed Motion", "CR2450", 1, 95, 1],
  ["Mailbox Sensor", "AAA", 1, 11, 15],
  ["Wine Cellar Temp", "CR2032", 1, 45, 9],
  ["Attic Smoke Alarm", "9V", 1, 7, 20],
  ["Side Gate Sensor", "CR2032", 1, 80, 3],
  ["Guest Room Motion", "CR2450", 1, 30, 11],
  ["Laundry Leak Sensor", "CR2", 1, 4, 26],
  ["Porch Light Sensor", "AAA", 2, 50, 7],
  ["Study Window", "CR2032", 1, 90, 2],
  ["Nursery Motion", "CR2450", 1, 13, 17],
  ["Driveway Sensor", "AA", 2, 65, 5],
  ["Pantry Door", "CR2032", 1, 10, 19],
  ["Garden Shed Temp", "AAA", 1, 38, 10],
  ["Utility Room Leak", "CR2", 1, 72, 4],
  ["Balcony Door", "CR2032", 1, 5, 23],
  ["Cat Flap Sensor", "AA", 3, 48, 8],
  ["Greenhouse Temp", "AAA", 2, 85, 2],
  ["Workshop Motion", "CR2450", 1, 9, 21],
];

const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
const entityOf = (n) => `sensor.${slug(n)}_battery`;

// ── 1. write the template-sensor package ─────────────────────────────────────
const sensors = FLEET.map(([name, , , level]) => `      - name: "${name} Battery"
        unique_id: bf_${slug(name)}_battery
        unit_of_measurement: "%"
        device_class: battery
        state_class: measurement
        state: "${level}"`).join("\n");
const pkg = `# Auto-generated by e2e/seed-battery-fleet.mjs — battery-fleet test fixture.\ntemplate:\n  - sensor:\n${sensors}\n`;
fs.mkdirSync(CFG + "packages", { recursive: true });
fs.writeFileSync(CFG + "packages/battery_fleet.yaml", pkg);
log("wrote packages/battery_fleet.yaml with", FLEET.length, "battery sensors");

// ensure the packages include in configuration.yaml
const cfgFile = CFG + "configuration.yaml";
let conf = fs.readFileSync(cfgFile, "utf8");
if (!/packages:\s*!include_dir_named packages/.test(conf)) {
  conf = conf.replace(/^homeassistant:/m, "homeassistant:\n  packages: !include_dir_named packages");
  fs.writeFileSync(cfgFile, conf);
  log("added packages include to configuration.yaml");
}

// ── 2. restart ha-maint, wait for the source entities ────────────────────────
const TOKEN = execSync("grep HA_TOKEN docker/.env | cut -d= -f2", {
  cwd: new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"),
}).toString().trim();
const auth = { Authorization: `Bearer ${TOKEN}`, "Content-Type": "application/json" };

log("restarting ha-maint…");
execSync("docker restart ha-maint", { stdio: "ignore" });
async function waitApi() {
  for (let i = 0; i < 60; i++) {
    try {
      const r = await fetch(`${REST}/api/config`, { headers: auth });
      if (r.ok) return;
    } catch { /* not up */ }
    await new Promise((s) => setTimeout(s, 5000));
  }
  throw new Error("ha-maint did not come up");
}
await waitApi();
await new Promise((s) => setTimeout(s, 8000)); // let templates + battery_notes settle
log("ha-maint up");

// HA's own clock (faketime-aware) for last-replaced spread.
const nowIso = await fetch(`${REST}/api/template`, {
  method: "POST", headers: auth, body: JSON.stringify({ template: "{{ now().isoformat() }}" }),
}).then((r) => r.text());
const now = new Date(nowIso.replace(/"/g, ""));
log("HA now =", now.toISOString());

// ── 3. drive Battery Notes' SUBENTRY flow per source entity ──────────────────
// Notes are subentries of the single Battery Notes hub entry (HA subentry
// feature): user -> entity -> battery. Driven via the subentries flow endpoint
// so the entries are always schema-valid.
const entries = await fetch(`${REST}/api/config/config_entries/entry`, { headers: auth }).then(j);
const hub = entries.find((e) => e.domain === "battery_notes");
if (!hub) throw new Error("Battery Notes hub entry not found — is battery_notes installed?");
const SUB = "/api/config/config_entries/subentries/flow";
async function sub(url, body) {
  const r = await fetch(REST + url, { method: "POST", headers: auth, body: JSON.stringify(body) });
  return await r.json().catch(() => null);
}
let created = 0, exists = 0, failed = 0;
for (const [name, type, qty] of FLEET) {
  const src = entityOf(name);
  let step = await sub(SUB, { handler: [hub.entry_id, "battery_note"] });
  if (step?.menu_options) step = await sub(`${SUB}/${step.flow_id}`, { next_step_id: "entity" });
  step = await sub(`${SUB}/${step.flow_id}`, { source_entity_id: src });
  if (step?.step_id === "battery") {
    step = await sub(`${SUB}/${step.flow_id}`, {
      battery_type: type, battery_quantity: qty, note: "", battery_low_threshold: 10, advanced_settings: {},
    });
  }
  if (step?.type === "create_entry") created++;
  else if (step?.reason === "already_configured") exists++;
  else { failed++; if (failed <= 3) log("  FAILED for", src, "->", JSON.stringify(step)?.slice(0, 180)); }
}
log(`notes: ${created} created, ${exists} already existed, ${failed} failed`);

// Let HA flush core.config_entries (delayed save) before we trust the count —
// a premature restart here would DROP freshly created subentries.
log("settling (config-entries flush)…");
await new Promise((s) => setTimeout(s, 15000));

// NOTE: battery_last_replaced is stamped to ~now at creation. We deliberately
// do NOT patch the battery_notes store + restart (that races the config-entry
// flush and loses subentries). Prediction correctness is proven in unit tests
// with synthetic last_replaced dates; this live fixture exercises
// discovery/setup with realistic fleet scale + type mix + low states.

// ── verify (battery_low is an ATTRIBUTE on battery_plus, not a binary) ────────
const states = await fetch(`${REST}/api/states`, { headers: auth }).then(j);
const plus = states.filter((s) => s.entity_id.endsWith("_battery_plus"));
const low = plus.filter((s) => s.attributes?.battery_low === true);
const types = {};
const need = {};
for (const s of plus) {
  const t = s.attributes?.battery_type;
  const q = s.attributes?.battery_quantity || 1;
  if (t) types[t] = (types[t] || 0) + q;
  if (t && s.attributes?.battery_low === true) need[t] = (need[t] || 0) + q;
}
log(`\nVERIFY: ${plus.length} battery_plus, ${low.length} currently LOW`);
log("types across fleet (qty):", JSON.stringify(types));
log("needed now by type:", JSON.stringify(need));
log("DONE");
